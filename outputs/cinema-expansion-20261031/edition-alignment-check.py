from pathlib import Path
import hashlib, json, re
from pypdf import PdfReader
import pdfplumber

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'outputs/cinema-expansion-20261031'
site = json.loads((ROOT / 'projects/site/src/data/cinema.json').read_text())
order = [s for p in site['parts'] for s in p['chapters']]
results = []
for edition in ('digital', 'print'):
    receipt_path = ROOT / 'tmp/pdfs/2026-10-31-aligned' / edition / 'book-build-2026-10-31-aligned.json'
    receipt = json.loads(receipt_path.read_text())
    path = ROOT / receipt['pdf']
    pdf = PdfReader(path)
    errors, external, internal = [], [], 0
    page_ids = {p.indirect_reference.idnum for p in pdf.pages}
    if [c['slug'] for c in receipt['chapters']] != order:
        errors.append('Chapter order differs from the online series')
    for c in receipt['chapters']:
        if hashlib.sha256((ROOT / c['source']).read_bytes()).hexdigest() != c['source_sha256']:
            errors.append('Stale chapter: ' + c['slug'])
    if not receipt['chapter_page_references_stable']:
        errors.append('Printed page references are not stable')
    if len(receipt['image_placements']) != 56 or len({i['sha256'] for i in receipt['image_placements']}) != 56:
        errors.append('Image placement or uniqueness mismatch')
    for item in receipt['image_placements']:
        if hashlib.sha256((ROOT / item['source']).read_bytes()).hexdigest() != item['sha256']:
            errors.append('Stale image: ' + item['source'])
    for n, page in enumerate(pdf.pages, 1):
        if list(map(float, page.mediabox)) != [0., 0., 432., 648.]:
            errors.append('Unexpected trim size on page ' + str(n))
        for ref in page.get('/Annots', []):
            ann = ref.get_object()
            action = ann.get('/A', {})
            dest = ann.get('/Dest') or action.get('/D')
            if dest:
                internal += 1
                if isinstance(dest, list) and getattr(dest[0], 'idnum', None) not in page_ids:
                    errors.append('Invalid internal link on page ' + str(n))
            if action.get('/URI'):
                uri = str(action['/URI']); external.append(uri)
                if re.search(r'file:|127\.0\.0\.1|localhost|/kb/|/blob/main/', uri):
                    errors.append('Internal-only URL: ' + uri)
    outside, texts = [], []
    with pdfplumber.open(path) as pp:
        for n, page in enumerate(pp.pages, 1):
            texts.append(page.extract_text() or '')
            if any(c['x0'] < -.5 or c['x1'] > 432.5 or c['top'] < -.5 or c['bottom'] > 648.5 for c in page.chars):
                outside.append(n)
    if outside:
        errors.append('Text outside trim: ' + str(outside))
    joined = '\n'.join(texts)
    disclosure_terms = ['AI-generated', 'Generated by AI', 'ChatGPT', 'Human Natural skill']
    for term in disclosure_terms:
        if term.casefold() in joined.casefold():
            errors.append('Repeated process disclosure: ' + term)
    for phrase in ['BPFTIO', 'Shreyas Sahil', 'Tara', '50 readings in 7 parts']:
        if phrase not in joined:
            errors.append('Missing updated passage: ' + phrase)
    if edition == 'print' and len(pdf.pages) % 2:
        errors.append('Print page count is not even')
    result = {
        'edition': edition, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
        'bytes': path.stat().st_size, 'pages': len(pdf.pages), 'chapters': len(order),
        'image_placements': 56, 'unique_originals': 56,
        'notes': receipt['notes'], 'citation_pairs': receipt['citation_pairs'],
        'internal_links': internal, 'external_links': len(external),
        'section_bookmark_matches': receipt['section_guide_matches'],
        'text_outside_trim': outside, 'errors': errors,
        'limits': 'Structure and text checks do not replace visual review or certify historical facts.'
    }
    results.append(result)
    print(json.dumps(result))
(OUT / 'edition-alignment-structure.json').write_text(json.dumps(results, indent=2) + '\n')
raise SystemExit(1 if any(r['errors'] for r in results) else 0)
