import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const story=JSON.parse(readFileSync(new URL('../../../kb/research/culture/ghanta-ghanti-website.json',import.meta.url),'utf8'));
const html=readFileSync(new URL('../dist-coast/sounds-of-odisha/ghanta-ghanti/index.html',import.meta.url),'utf8');
test('full Ghanta and ghanti reader text and sources survive with collection return and honest limits',()=>{
 for(const block of story.blocks) for(const p of [...block.paragraphs,...block.items]) assert.ok(html.includes(p.replaceAll('&','&amp;').replaceAll("'",'&#39;').replaceAll('"','&quot;').replaceAll('<','&lt;').replaceAll('>','&gt;')),p);
 assert.ok(html.includes('href="/sounds-of-odisha/#ghanta-ghanti"'));
 for(const s of story.sources)assert.ok(html.includes(s.resource));
 assert.ok(html.includes('not counted as independent corroboration'));
 assert.ok(html.includes('2004'));
 assert.ok(html.includes('16–20'));
 assert.ok(html.indexOf('three small acts of attention:')<html.indexOf('Notice the moment the ringing begins'));
 assert.ok(html.indexOf('Ask a maker or player')<html.indexOf('Follow the host'));
 assert.ok(html.includes('not a technique guide'));
 assert.ok(!html.includes('<audio'));
 assert.ok(html.includes('href="/sounds-of-odisha/sankha/"'));
 assert.ok(html.includes('href="/sounds-of-odisha/huluhuli/"'));
 for(const step of story.listening_panel.steps) assert.ok(html.includes(step.prompt)); 
 assert.ok(html.includes('Practitioner/language review remains open'));
 assert.ok(!html.includes('<audio'));
 assert.ok(!html.includes('Preserved research overview'));
 assert.ok(readFileSync(new URL('../dist-coast/sounds-of-odisha/index.html',import.meta.url),'utf8').includes('href="/sounds-of-odisha/ghanta-ghanti/"'));
});
